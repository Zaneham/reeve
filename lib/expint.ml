let dcbrt x =
  if x = 0.0 then 0.0
  else begin
    let y, n = d9upak (Float.abs x) in
    let ixpnt = n / 3 in
    let irem = n - (3 * ixpnt) + 3 in
    let z = single y in
    let r =
      ref
        (single
           (single 0.439581
           +. single
                (z
                *. single
                     (single 0.928549
                     +. single
                          (z
                          *. single
                               (single (-0.512653)
                               +. single (z *. single 0.144586)))))))
    in
    for _iter = 1 to dcbrt_niter do
      let cbrtsq = !r *. !r in
      r := !r +. ((y -. (!r *. cbrtsq)) /. (3.0 *. cbrtsq))
    done;
    d9pak (cbrt2.(irem - 1) *. Float.copy_sign !r x) ixpnt
  end

let dexprl x =
  let absx = Float.abs x in
  if absx > 0.5 then (exp x -. 1.0) /. x
  else if absx < dexprl_xbnd then 1.0
  else begin
    let r = ref 0.0 in
    for i = 1 to dexprl_nterms do
      r := 1.0 +. (!r *. x /. float_of_int (dexprl_nterms + 2 - i))
    done;
    !r
  end

let dlnrel x =
  if x <= -1.0 then invalid_arg "dlnrel: x is <= -1"
  else if Float.abs x <= 0.375 then
    x *. (1.0 -. (x *. Specfun.dcsevl (x /. 0.375) alnrcs nlnrel))
  else log (1.0 +. x)

let d9ln2r x =
  if x > d9ln2r_xmax then
    invalid_arg "d9ln2r: no precision in answer because x is too big"
  else if x < -0.625 || x > 0.8125 then
    (log (1.0 +. x) -. (x *. (1.0 -. (0.5 *. x)))) /. ((x *. x) *. x)
  else if x < 0.0 then
    0.375 +. Specfun.dcsevl ((16.0 *. x /. 5.0) +. 1.0) ln21cs ntln21
  else 0.375 +. Specfun.dcsevl ((32.0 *. x /. 13.0) -. 1.0) ln22cs ntln22

let d9atn1 x =
  let y = Float.abs x in
  if y > d9atn1_xmax then
    invalid_arg "d9atn1: no precision in answer because x is too big"
  else if y > 1.0 then (atan x -. x) /. ((x *. x) *. x)
  else if y > d9atn1_xsml then
    -0.25 +. Specfun.dcsevl (((2.0 *. y) *. y) -. 1.0) atn1cs ntatn1
  else -1.0 /. 3.0

let dsindg x =
  let r = sin (raddeg *. x) in
  if Float.rem x 90.0 <> 0.0 then r
  else begin
    let n = int_of_float ((Float.abs x /. 90.0) +. 0.5) mod 2 in
    if n = 0 then 0.0 else Float.copy_sign 1.0 r
  end

let dcosdg x =
  let r = cos (raddeg *. x) in
  if Float.rem x 90.0 <> 0.0 then r
  else begin
    let n = int_of_float ((Float.abs x /. 90.0) +. 0.5) mod 2 in
    if n = 0 then Float.copy_sign 1.0 r else 0.0
  end

(* ---- Spence's integral ---- *)

let dspenc x =
  if x > 2.0 then begin
    let r = (2.0 *. pi26) -. (0.5 *. (log x *. log x)) in
    if x < dspenc_xbig then
      r -. ((1.0 +. Specfun.dcsevl ((4.0 /. x) -. 1.0) spencs nspenc) /. x)
    else r
  end
  else if x > 1.0 then
    pi26
    -. (0.5 *. log x *. log (((x -. 1.0) *. (x -. 1.0)) /. x))
    +. ((x -. 1.0)
        *. (1.0 +. Specfun.dcsevl ((4.0 *. (x -. 1.0) /. x) -. 1.0) spencs nspenc)
        /. x)
  else if x > 0.5 then
    if x <> 1.0 then
      pi26
      -. (log x *. log (1.0 -. x))
      -. ((1.0 -. x)
          *. (1.0 +. Specfun.dcsevl ((4.0 *. (1.0 -. x)) -. 1.0) spencs nspenc))
    else pi26
  else if x >= 0.0 then
    x *. (1.0 +. Specfun.dcsevl ((4.0 *. x) -. 1.0) spencs nspenc)
  else if x > -1.0 then
    (-0.5 *. (log (1.0 -. x) *. log (1.0 -. x)))
    -. (x
        *. (1.0 +. Specfun.dcsevl ((4.0 *. x /. (x -. 1.0)) -. 1.0) spencs nspenc)
        /. (x -. 1.0))
  else begin
    let aln = log (1.0 -. x) in
    let r = -.pi26 -. (0.5 *. aln *. ((2.0 *. log (-.x)) -. aln)) in
    if x > -.dspenc_xbig then
      r
      +. ((1.0 +. Specfun.dcsevl ((4.0 /. (1.0 -. x)) -. 1.0) spencs nspenc)
          /. (1.0 -. x))
    else r
  end

(* ---- Exponential integrals ---- *)

let de1 x =
  if x = 0.0 then invalid_arg "de1: x is 0"
  else if x > de1_xmax then 0.0
  else if x > 4.0 then
    exp (-.x) /. x *. (1.0 +. Specfun.dcsevl ((8.0 /. x) -. 1.0) ae14cs ntae14)
  else if x > 1.0 then
    exp (-.x) /. x *. (1.0 +. Specfun.dcsevl (((8.0 /. x) -. 5.0) /. 3.0) ae13cs ntae13)
  else if x > -1.0 then
    -.log (Float.abs x) -. 0.6875 +. x +. Specfun.dcsevl x e12cs nte12
  else if x > -4.0 then
    -.log (-.x) +. Specfun.dcsevl (((2.0 *. x) +. 5.0) /. 3.0) e11cs nte11
  else if x > -8.0 then
    exp (-.x) /. x *. (1.0 +. Specfun.dcsevl ((16.0 /. x) +. 3.0) ae12cs ntae12)
  else if x > -32.0 then
    exp (-.x) /. x
    *. (1.0 +. Specfun.dcsevl (((64.0 /. x) +. 5.0) /. 3.0) ae11cs ntae11)
  else exp (-.x) /. x *. (1.0 +. Specfun.dcsevl ((64.0 /. x) +. 1.0) ae10cs ntae10)

let dei x = -.de1 (-.x)

let dli x =
  if x <= 0.0 then invalid_arg "dli: log integral undefined for x <= 0";
  if x = 1.0 then invalid_arg "dli: log integral undefined for x = 1";
  dei (log x)

(* ---- Dawson's function ---- *)

let ddaws x =
  let y = Float.abs x in
  if y <= ddaws_xsml then x
  else if y <= 1.0 then
    x *. (0.75 +. Specfun.dcsevl (((2.0 *. y) *. y) -. 1.0) dawcs ntdaw)
  else if y <= 4.0 then
    x *. (0.25 +. Specfun.dcsevl (((0.125 *. y) *. y) -. 1.0) daw2cs ntdaw2)
  else if y <= ddaws_xbig then
    (0.5 +. Specfun.dcsevl ((32.0 /. (y *. y)) -. 1.0) dawacs ntdawa) /. x
  else if y <= ddaws_xmax then 0.5 /. x
  else if y > ddaws_xmax then 0.0
  else x

(* ---- The exponential integral sequence ---- *)

let dpsixn n =
  if n < 1 then invalid_arg "dpsixn: n < 1";
  if n > 100 then begin
    let wdtol = Float.max eps_dp 1.0e-18 in
    let fn = float_of_int n in
    let ax = ref 1.0 in
    let s = ref (-0.5 /. fn) in
    if Float.abs !s > wdtol then begin
      let rfn2 = 1.0 /. (fn *. fn) in
      let k = ref 1 and stop = ref false in
      while (not !stop) && !k <= 6 do
        ax := !ax *. rfn2;
        let trm = -.psixn_b.(!k - 1) *. !ax in
        if Float.abs trm < wdtol then stop := true
        else begin
          s := !s +. trm;
          incr k
        end
      done
    end;
    !s +. log fn
  end
  else psixn_c.(n - 1)

