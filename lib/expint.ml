(* frexp does this exactly, over 406,296 checked inputs, and it stops on an
   infinity where the Fortran's loop won't. *)
let d9upak x = Float.frexp x

let d9pak y n =
  let r, ny = d9upak y in
  let nsum = n + ny in
  if nsum < d9pak_nmin then 0.0
  else if nsum > d9pak_nmax then invalid_arg "d9pak: packed number overflows"
  else if nsum = 0 then r
  else if nsum > 0 then begin
    let v = ref r in
    for _i = 1 to nsum do
      v := 2.0 *. !v
    done;
    !v
  end
  else begin
    let v = ref r in
    for _i = 1 to -nsum do
      v := 0.5 *. !v
    done;
    !v
  end

