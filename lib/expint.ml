(* dexint.inc drops into the Miller block where the original jumps past it,
   clobbering the series for x up to 2 with m above 1. This follows the
   original. *)
let dexint x n kode m tol en =
  let etol = Float.max eps_dp 0.5e-18 in
  if x < 0.0 then invalid_arg "dexint: x < 0";
  if n < 1 then invalid_arg "dexint: n < 1";
  if kode < 1 || kode > 2 then invalid_arg "dexint: kode not 1 or 2";
  if m < 1 then invalid_arg "dexint: m < 1";
  if tol < etol || tol > 0.1 then invalid_arg "dexint: tol out of range";
  if x = 0.0 && n = 1 then invalid_arg "dexint: x = 0 with n = 1";
  let i1m = -min_exp_dp in
  let pt = 2.3026 *. float_of_int i1m *. log10_radix_dp in
  let bt = pt +. float_of_int (n + m - 1) in
  let xlim = if bt > 1000.0 then pt -. log bt else pt -. 6.907755 in
  let a = Array.make 99 0.0 and b = Array.make 99 0.0 in
  let nz = ref 0 in
  let emx = ref 1.0 in
  let icase = ref 0
  and ks = ref 0
  and ml = ref 0
  and mu = ref 0
  and ind = ref 0 in
  let recurse aa0 =
    let aa = ref aa0 in
    if !icase = 1 then begin
      let k = ref (!ind - 1) in
      for _i = 1 to !ml do
        aa := !aa -. 1.0;
        en.(!k - 1) <- (!emx -. (!aa *. en.(!k))) /. x;
        k := !k - 1
      done;
      if !mu <= 0 then raise Dexint_done;
      aa := float_of_int !ks
    end;
    let k = ref !ind in
    for _i = 1 to !mu do
      en.(!k) <- (!emx -. (x *. en.(!k - 1))) /. !aa;
      aa := !aa +. 1.0;
      k := !k + 1
    done
  in
  let miller () =
    let ik = !ks / 2 in
    let ah = float_of_int ik in
    let jset = 1 + !ks - (ik + ik) in
    let ic = ref 0 in
    let aa = ah +. ah in
    let aams = (aa -. 1.0) *. (aa -. 1.0) in
    let tx = x +. x in
    let fx = tx +. tx in
    let ak = ref ah in
    let xtol = if tol <= 1.0e-3 then 20.0 *. tol else tol in
    let ct = ref (aams +. (fx *. ah)) in
    let em = ref ((ah +. 1.0) /. ((x +. aa) *. xtol *. sqrt !ct)) in
    let bk = ref aa in
    let cc = ah *. ah in
    let p1 = ref 0.0 and p2 = ref 1.0 in
    let converged = ref false in
    while not !converged do
      if !ic = 99 then invalid_arg "dexint: termination condition not met";
      incr ic;
      ak := !ak +. 1.0;
      let at = !bk /. (!bk +. !ak +. cc +. float_of_int !ic) in
      bk := !bk +. !ak +. !ak;
      a.(!ic - 1) <- at;
      let bt = (!ak +. !ak +. x) /. (!ak +. 1.0) in
      b.(!ic - 1) <- bt;
      let pt = !p2 in
      p2 := (bt *. !p2) -. (at *. !p1);
      p1 := pt;
      ct := !ct +. fx;
      em := !em *. at *. (1.0 -. (tx /. !ct));
      if !em *. (!ak +. 1.0) <= !p1 *. !p1 then converged := true
    done;
    let ict = !ic in
    let kk = ref (!ic + 1) in
    let bt = tx /. (!ct +. fx) in
    let y2 =
      ref
        (!bk
        /. (!bk +. cc +. float_of_int !kk)
        *. (!p1 /. !p2)
        *. (1.0 -. bt +. (0.375 *. bt *. bt)))
    in
    let y1 = ref 1.0 in
    for _k = 1 to ict do
      kk := !kk - 1;
      let yt = !y1 in
      y1 := ((b.(!kk - 1) *. !y1) -. !y2) /. a.(!kk - 1);
      y2 := yt
    done;
    let pt = !y2 /. !y1 in
    let cnorm = 1.0 -. (pt *. (ah +. 1.0) /. aa) in
    let yy1 = 1.0 /. ((cnorm *. aa) +. x) in
    let yy2 = cnorm *. yy1 in
    if !icase = 3 then begin
      en.(0) <- !emx *. (1.0 -. yy1) /. x;
      raise Dexint_done
    end;
    en.(!ind - 1) <- !emx *. (if jset = 1 then yy1 else yy2);
    if m = 1 then raise Dexint_done;
    recurse (float_of_int !ks)
  in
  (try
     if x > dexint_xcut then begin
       emx := 1.0;
       if kode <> 2 then
         if x <= xlim then emx := exp (-.x)
         else begin
           nz := m;
           for i = 1 to m do
             en.(i - 1) <- 0.0
           done;
           raise Dexint_done
         end;
       let ix = ref (int_of_float (x +. 0.5)) in
       let kn = n + m - 1 in
       let set150 () =
         ks := 2;
         icase := 3
       in
       let set170 () =
         icase := 1;
         ks := !ix;
         ml := !ix - n;
         ind := !ml + 1;
         mu := kn - !ix
       in
       if kn <= !ix then begin
         icase := 1;
         ks := kn;
         ml := m - 1;
         mu := -1;
         ind := m;
         if kn <= 1 then set150 ()
       end
       else if n < !ix && !ix < kn then set170 ()
       else if n >= !ix then begin
         icase := 2;
         ind := 1;
         ks := n;
         mu := m - 1;
         if n <= 1 then
           if kn = 1 then set150 ()
           else begin
             ix := 2;
             set170 ()
           end
       end
       else invalid_arg "dexint: termination condition not met";
       miller ()
     end
     else if x = 0.0 && n > 1 then
       for i = 1 to m do
         en.(i - 1) <- 1.0 /. float_of_int (n + i - 2)
       done
     else begin
       let ix = int_of_float (x +. 0.5) in
       icase := (if ix > n then 1 else 2);
       let nm = n - !icase + 1 in
       let nd = nm + 1 in
       ind := 3 - !icase;
       mu := m - !ind;
       ml := 1;
       ks := nd;
       let fnm = float_of_int nm in
       let s = ref 0.0 in
       let xtol = ref (3.0 *. tol) in
       if nd <> 1 then begin
         xtol := 0.3333 *. tol;
         s := 1.0 /. fnm
       end;
       let aa = ref 1.0 and ak = ref 1.0 in
       let ic = if x < etol then 1 else 35 in
       let skip50 = ref false in
       let i = ref 1 in
       while (not !skip50) && !i <= ic do
         aa := -. !aa *. x /. !ak;
         if !i = nm then begin
           s := !s +. (!aa *. (-.log x +. dpsixn nd));
           xtol := 3.0 *. tol;
           ak := !ak +. 1.0
         end
         else begin
           s := !s -. (!aa /. (!ak -. fnm));
           if Float.abs !aa <= !xtol *. Float.abs !s then
             if !i < 2 then ak := !ak +. 1.0
             else if nd - 2 > !i || !i > nd - 1 then skip50 := true
             else ak := !ak +. 1.0
           else ak := !ak +. 1.0
         end;
         if not !skip50 then incr i
       done;
       if (not !skip50) && ic <> 1 then
         invalid_arg "dexint: series did not converge";
       if nd = 1 then s := !s +. (-.log x +. dpsixn 1);
       if kode = 2 then s := !s *. exp x;
       en.(0) <- !s;
       emx := 1.0;
       if m = 1 then begin
         if !icase = 2 then raise Dexint_done;
         if kode = 1 then emx := exp (-.x);
         en.(0) <- (!emx -. !s) /. x;
         raise Dexint_done
       end;
       en.(!ind - 1) <- !s;
       if kode = 1 then emx := exp (-.x);
       recurse (float_of_int !ks)
     end
   with Dexint_done -> ());
  !nz
