let dcsevl x cs n =
  if Float.abs x > 1.0 then
    invalid_arg "dcsevl: x outside the interval (-1,+1)";
  let twox = 2.0 *. x in
  let b0 = ref 0.0 and b1 = ref 0.0 and b2 = ref 0.0 in
  for i = 1 to n do
    b2 := !b1;
    b1 := !b0;
    b0 := (twox *. !b1) -. !b2 +. cs.(n - i)
  done;
  0.5 *. (!b0 -. !b2)

